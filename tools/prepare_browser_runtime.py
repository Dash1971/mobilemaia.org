#!/usr/bin/env python3
"""Derive the 5M-only memory-bounded loader from the pinned ORT distribution."""
import argparse, hashlib, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
UPSTREAM = ROOT/'site/lab/inference/vendor/ort-wasm-simd-threaded.mjs'
OUTPUT = ROOT/'site/play/native/ort-5m-256m.mjs'
UPSTREAM_SHA256 = '30ed0b5cd1182ede931fea448afb567d4dc705ec957af09f108a2be5f770dac3'

def expected():
    data = UPSTREAM.read_bytes()
    if hashlib.sha256(data).hexdigest() != UPSTREAM_SHA256:
        raise ValueError('Review the memory adaptation against the updated pinned ORT loader.')
    text = data.decode()
    # The Wasm binary imports memory with a 4 GiB upper limit. A smaller imported
    # memory maximum is valid; kernels/model bytes and initial 16 MiB are unchanged.
    for old, new in [('initial:256,maximum:65536,shared:!0', 'initial:256,maximum:4096,shared:!0')]:
        if text.count(old) != 1: raise ValueError('Unexpected Emscripten allocation/growth code: '+old)
        text = text.replace(old, new)
    # Keep the C heap-limit query, resize rejection and growth clamp consistent.
    if text.count('4294901760') != 3: raise ValueError('Unexpected Emscripten heap-limit sites.')
    text = text.replace('4294901760', '268435456')
    return ('// Generated by tools/prepare_browser_runtime.py from ONNX Runtime Web 1.31.1.\n'
            '// Microsoft MIT license: ../../lab/inference/vendor/LICENSE.\n'
            '// 5M only: shared memory maximum/growth capped at 256 MiB, initial 16 MiB.\n'
            '// Model and Wasm binary are unchanged. See docs/WEB_ADAPTATIONS.md W01.\n'+text).encode()

def check():
    if not OUTPUT.exists() or OUTPUT.read_bytes() != expected():
        raise ValueError('Regenerate the 5M loader with tools/prepare_browser_runtime.py.')
    print('PASS: 5M loader is the exact pinned ORT source with only memory maximum/growth changes.')

if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    if args.check: check()
    else: OUTPUT.write_bytes(expected())
